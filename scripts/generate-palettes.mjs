import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const palettesDir = path.join(root, 'styles', 'palettes');
const distDir = path.join(root, 'dist');
const defaultMetaPath = path.join(__dirname, 'palette-default.json');
const colorsCssPath = path.join(root, 'styles', 'colors.css');

const INDEX_BASENAME = 'index.css';

/** @param {string} source @param {string} context */
function parseTheme500(source, context) {
  const match = source.match(/--theme-500:\s*([^;]+);/);

  if (!match) {
    throw new Error(`${context}: missing --theme-500`);
  }

  return match[1].trim();
}

/** @param {string} source */
function parsePaletteMeta(source, id) {
  const blockMatch = source.match(/\/\*\s*@palette\s*([\s\S]*?)\*\//);
  if (!blockMatch) {
    throw new Error(`styles/palettes/${id}.css: missing /* @palette ... */ metadata block`);
  }

  const block = blockMatch[1];
  const labelMatch = block.match(/^\s*label:\s*(.+)\s*$/m);
  const introMatch = block.match(/^\s*intro:\s*(.+)\s*$/m);

  if (!labelMatch || !introMatch) {
    throw new Error(`styles/palettes/${id}.css: @palette block must include label: and intro:`);
  }

  return {
    id,
    label: labelMatch[1].trim(),
    intro: introMatch[1].trim(),
    swatch: parseTheme500(source, `styles/palettes/${id}.css`),
  };
}

async function main() {
  const defaultMeta = JSON.parse(await readFile(defaultMetaPath, 'utf8'));
  const colorsCss = await readFile(colorsCssPath, 'utf8');
  const defaultSwatch = parseTheme500(colorsCss, 'styles/colors.css');
  const entries = await readdir(palettesDir, { withFileTypes: true });
  const paletteFiles = entries
    .filter((entry) => entry.isFile() && entry.name.endsWith('.css') && entry.name !== INDEX_BASENAME)
    .map((entry) => entry.name)
    .sort();

  const palettes = [];
  for (const filename of paletteFiles) {
    const id = filename.replace(/\.css$/, '');
    const source = await readFile(path.join(palettesDir, filename), 'utf8');
    palettes.push(parsePaletteMeta(source, id));
  }

  const indexCss = [
    '/* Generated by scripts/generate-palettes.mjs — do not edit. */',
    '/* Import after core.css; set data-palette on <html> per palettes.json. */',
    ...paletteFiles.map((filename) => `@import './${filename}';`),
    '',
  ].join('\n');

  const manifest = {
    default: {
      id: null,
      label: defaultMeta.label,
      intro: defaultMeta.intro,
      swatch: defaultSwatch,
    },
    palettes,
  };

  await writeFile(path.join(palettesDir, INDEX_BASENAME), indexCss, 'utf8');
  await mkdir(distDir, { recursive: true });
  await writeFile(path.join(distDir, 'palettes.json'), `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');

  console.log(`generate-palettes: ${paletteFiles.length} palette(s) → styles/palettes/index.css, dist/palettes.json`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
